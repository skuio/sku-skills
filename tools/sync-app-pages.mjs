#!/usr/bin/env node
// Regenerate tools/data/app-pages.json — the SKU.io web app's page routes — from an app checkout.
//
//   npm run sync:app-pages -- --source ~/code/sku                     # the working tree
//   npm run sync:app-pages -- --source ~/code/sku --ref origin/master  # a git ref, no checkout
//
// `npm run validate` checks every page link a skill hands back (and every `pages:` entry)
// against this file, so a link that 404s fails CI. Re-run it when the app moves a page, and
// whenever validate reports a link you know is real.
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { APP_PAGES_FILE, routeForPageFile } from './lib/app-pages.mjs';
import { writeFile } from './lib/fs.mjs';

const PAGES_DIR = 'frontend-vue-3/src/pages';
const arg = (name) => {
  const i = process.argv.indexOf(name);
  return i === -1 ? undefined : process.argv[i + 1];
};
const source = arg('--source');
const ref = arg('--ref');
if (!source) {
  console.error('✗ Pass --source <sku app checkout> [--ref <git ref>].');
  process.exit(2);
}

function pageFiles() {
  if (ref) {
    const out = execFileSync('git', ['-C', source, 'ls-tree', '-r', '--name-only', ref, '--', PAGES_DIR], {
      encoding: 'utf8', maxBuffer: 64 * 1024 * 1024,
    });
    return out.split('\n').filter(Boolean).map((f) => f.slice(PAGES_DIR.length + 1));
  }
  const root = path.join(source, PAGES_DIR);
  const files = [];
  const walk = (dir) => {
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, e.name);
      if (e.isDirectory()) walk(full);
      else files.push(path.relative(root, full).split(path.sep).join('/'));
    }
  };
  walk(root);
  return files;
}

let files;
try {
  files = pageFiles();
} catch (err) {
  console.error(`✗ Could not read ${PAGES_DIR} from ${source}${ref ? ` at ${ref}` : ''}: ${err.message}`);
  process.exit(2);
}
const routes = [...new Set(files.map(routeForPageFile).filter(Boolean))].sort();
if (routes.length < 100) {
  console.error(`✗ Only ${routes.length} routes found under ${PAGES_DIR} — is ${source} a SKU.io app checkout?`);
  process.exit(2);
}

let commit = null;
try {
  commit = execFileSync('git', ['-C', source, 'rev-parse', '--short', ref ?? 'HEAD'], { encoding: 'utf8' }).trim();
} catch {
  // not a git checkout; the routes still stand
}

writeFile(APP_PAGES_FILE, JSON.stringify({
  _note: 'Generated by `npm run sync:app-pages` from the SKU.io app\'s frontend-vue-3/src/pages. Paths are relative to /v2. Do not hand-edit.',
  source_commit: commit,
  routes,
}, null, 2));
console.log(`✓ ${routes.length} app page routes${commit ? ` from ${commit}` : ''} → ${path.relative(process.cwd(), APP_PAGES_FILE)}`);
